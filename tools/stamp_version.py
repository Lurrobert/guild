#!/usr/bin/env python3
"""Writes src/version.py: the git commit and a SHA-256 over the Worker source, for GET /version.

Hash = SHA-256 of the lines "<file name>\\t<sha256 hex of the file>\\n" for every src/*.py except
version.py, sorted by name. verify.py recomputes it from a checkout. Run before every deploy:
    python3 tools/gen_docs.py && python3 tools/stamp_version.py --commit "$(git rev-parse HEAD)"
"""
import argparse
import hashlib
import os
import time

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "src")


def file_hashes(src=SRC):
    out = []
    for name in sorted(os.listdir(src)):
        if name.endswith(".py") and name != "version.py":
            with open(os.path.join(src, name), "rb") as handle:
                out.append([name, hashlib.sha256(handle.read()).hexdigest()])
    return out


def source_hash(files):
    return hashlib.sha256("".join(f"{n}\t{h}\n" for n, h in files).encode("utf-8")).hexdigest()


def render(commit, stamped_at):
    files = file_hashes()
    return ('"""Generated by tools/stamp_version.py at deploy time. Do not edit by hand."""\n\n'
            f"COMMIT = {commit!r}\nSTAMPED_AT = {int(stamped_at)!r}\nSOURCE_SHA256 = {source_hash(files)!r}\n"
            f"FILES = {files!r}\n")


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--commit", default="uncommitted")
    args = parser.parse_args()
    with open(os.path.join(SRC, "version.py"), "w", encoding="utf-8") as handle:
        handle.write(render(args.commit, time.time()))


if __name__ == "__main__":
    main()
