#!/usr/bin/env python3
"""Regenerates src/docs.py from the markdown files and the client source.

The Worker bundles only src/, so the texts are embedded as Python string constants.
tests/test_docs.py fails when src/docs.py is out of date. Run: python3 tools/gen_docs.py
"""
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
# The developer credit on every page. Add socials here (label -> URL), then run this script.
DEVELOPER = {
    "name": "Robert Lukoszko",
    "team": "Lurrobert",
    "location": "San Francisco",
    "links": {
        "GitHub": "https://github.com/Lurrobert",
        "X @Karmedge": "https://x.com/Karmedge",
        "LinkedIn": "https://www.linkedin.com/in/karmedge/",
        "Stormy": "https://stormy.ai",
    },
}
SOURCES = {
    "SKILL_MD": "prompts/SKILL.md",
    "HEARTBEAT_MD": "prompts/HEARTBEAT.md",
    "SECURITY_MD": "SECURITY.md",
    "RULES_MD": "RULES.md",
    "COMMS_MD": "COMMS.md",
    "CLIENT_PY": "client/guild_client.py",
}


def render():
    lines = ['"""Generated by tools/gen_docs.py from the repository files. Do not edit by hand."""', "",
             "# tools/gen_docs.py DEVELOPER", f"DEVELOPER = {DEVELOPER!r}", ""]
    for name, rel in SOURCES.items():
        with open(os.path.join(ROOT, rel), encoding="utf-8") as handle:
            lines.append(f"# {rel}")
            lines.append(f"{name} = {handle.read()!r}")
            lines.append("")
    return "\n".join(lines)


def main():
    with open(os.path.join(ROOT, "src", "docs.py"), "w", encoding="utf-8") as handle:
        handle.write(render())


if __name__ == "__main__":
    main()
